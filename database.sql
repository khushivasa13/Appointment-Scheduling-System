-- Appointment Scheduling System Database Setup

-- Create table to store faculty appointment slots
CREATE TABLE APPOINTMENT_SLOT (
    SLOT_ID NUMBER PRIMARY KEY,
    FACULTY_NAME VARCHAR2(100) NOT NULL,
    SLOT_TIME TIMESTAMP NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
    CONSTRAINT CHK_SLOT_STATUS
        CHECK (STATUS IN ('AVAILABLE', 'BOOKED'))
);

-- Create table to store student appointments
CREATE TABLE APPOINTMENT (
    APPOINTMENT_ID NUMBER PRIMARY KEY,
    SLOT_ID NUMBER NOT NULL UNIQUE,
    STUDENT_NAME VARCHAR2(100) NOT NULL,
    REASON VARCHAR2(200),
    BOOKING_STATUS VARCHAR2(20) DEFAULT 'BOOKED' NOT NULL,
    CONSTRAINT FK_APPT_SLOT FOREIGN KEY (SLOT_ID)
        REFERENCES APPOINTMENT_SLOT(SLOT_ID),
    CONSTRAINT CHK_BOOKING_STATUS
        CHECK (BOOKING_STATUS IN ('BOOKED', 'CANCELLED'))
);

-- Create sequence to generate appointment IDs
CREATE SEQUENCE APPOINTMENT_SEQ
START WITH 1
INCREMENT BY 1;

